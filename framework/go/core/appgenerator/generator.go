package appgenerator

import (
	"bytes"
	"crypto/sha256"
	"errors"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"strconv"

	"github.com/heiyeluren/mz-gui/framework/go/core/appmanifest"
	"github.com/heiyeluren/mz-gui/framework/go/core/capability"
)

var (
	ErrInvalidOptions = errors.New("应用元数据生成参数无效")
	ErrOutputOutdated = errors.New("应用元数据生成结果已过期")

	packagePattern = regexp.MustCompile(`^[a-z][a-z0-9_]*$`)
)

type Options struct {
	PackageName string
}

func Render(manifestData, catalogData []byte, options Options) ([]byte, error) {
	if !packagePattern.MatchString(options.PackageName) {
		return nil, ErrInvalidOptions
	}
	catalog, err := capability.Decode(catalogData)
	if err != nil {
		return nil, err
	}
	validated, err := appmanifest.Parse(manifestData, catalog)
	if err != nil {
		return nil, err
	}
	manifest := validated.Manifest
	releaseEligible := validated.ValidateProduction(catalog) == nil
	selectionDigest, err := validated.Selection.Digest()
	if err != nil {
		return nil, err
	}
	catalogDigest := sha256.Sum256(catalogData)
	manifestDigest := sha256.Sum256(manifestData)

	var source bytes.Buffer
	fmt.Fprintln(&source, "// Code generated by mzguiappgen. DO NOT EDIT. 此文件由工具生成，请勿手工修改。")
	fmt.Fprintf(&source, "package %s\n\n", options.PackageName)
	fmt.Fprintln(&source, "const (")
	writeStringConstant(&source, "AppID", manifest.App.ID)
	writeStringConstant(&source, "DisplayName", manifest.App.DisplayName)
	writeStringConstant(&source, "Description", manifest.App.Description)
	writeStringConstant(&source, "ProtocolScheme", manifest.App.ProtocolScheme)
	writeStringConstant(&source, "DataNamespace", manifest.App.DataNamespace)
	writeStringConstant(&source, "SingleInstanceID", manifest.App.SingleInstanceID)
	writeStringConstant(&source, "DesktopProcess", manifest.Processes.Desktop)
	writeStringConstant(&source, "AgentdProcess", manifest.Processes.Agentd)
	writeStringConstant(&source, "BrowserHostProcess", manifest.Processes.BrowserHost)
	writeStringConstant(&source, "HelperProcess", manifest.Processes.Helper)
	writeStringConstant(&source, "ConfigBasename", manifest.Storage.ConfigBasename)
	writeStringConstant(&source, "DatabaseBasename", manifest.Storage.DatabaseBasename)
	writeStringConstant(&source, "ArtifactNamespace", manifest.Storage.ArtifactNamespace)
	writeStringConstant(&source, "CredentialService", manifest.Security.CredentialService)
	writeStringConstant(&source, "MacOSBundleID", manifest.Build.MacOSBundleID)
	writeStringConstant(&source, "WindowsAppID", manifest.Build.WindowsAppID)
	fmt.Fprintf(&source, "\tCatalogSchemaVersion = %d\n", manifest.Framework.CapabilityCatalogVersion)
	fmt.Fprintf(&source, "\tCatalogRevision uint64 = %d\n", validated.Selection.CatalogRevision)
	writeStringConstant(&source, "FrameworkAPIVersion", validated.Selection.FrameworkAPIVersion)
	writeStringConstant(&source, "CatalogSHA256", fmt.Sprintf("%x", catalogDigest))
	writeStringConstant(&source, "ManifestSHA256", fmt.Sprintf("%x", manifestDigest))
	writeStringConstant(&source, "SelectionSHA256", selectionDigest)
	fmt.Fprintf(&source, "\tReleaseEligible = %t\n", releaseEligible)
	fmt.Fprintln(&source, ")")
	writeStringSliceAccessor(&source, "RequestedCapabilities", validated.Selection.Requested)
	writeStringSliceAccessor(&source, "ResolvedCapabilities", validated.Selection.Resolved)
	writeStringSliceAccessor(&source, "ReleaseChannels", manifest.Build.Channels)

	formatted, err := format.Source(source.Bytes())
	if err != nil {
		return nil, fmt.Errorf("格式化应用元数据: %w", err)
	}
	return formatted, nil
}

func GenerateFile(manifestPath, catalogPath, outputPath string, options Options) error {
	data, err := renderFiles(manifestPath, catalogPath, options)
	if err != nil {
		return err
	}
	return writeAtomic(outputPath, data)
}

func CheckFile(manifestPath, catalogPath, outputPath string, options Options) error {
	want, err := renderFiles(manifestPath, catalogPath, options)
	if err != nil {
		return err
	}
	current, err := os.ReadFile(outputPath)
	if err != nil {
		return err
	}
	if !bytes.Equal(canonicalGenerated(current), canonicalGenerated(want)) {
		return ErrOutputOutdated
	}
	return nil
}

func canonicalGenerated(data []byte) []byte {
	return bytes.ReplaceAll(data, []byte("\r\n"), []byte("\n"))
}

func renderFiles(manifestPath, catalogPath string, options Options) ([]byte, error) {
	manifestData, err := os.ReadFile(manifestPath)
	if err != nil {
		return nil, fmt.Errorf("读取应用 Manifest: %w", err)
	}
	catalogData, err := os.ReadFile(catalogPath)
	if err != nil {
		return nil, fmt.Errorf("读取能力 Catalog: %w", err)
	}
	return Render(manifestData, catalogData, options)
}

func writeAtomic(path string, data []byte) error {
	if path == "" || filepath.Base(path) != "manifest_gen.go" {
		return ErrInvalidOptions
	}
	if info, err := os.Lstat(path); err == nil && info.Mode()&os.ModeSymlink != 0 {
		return ErrInvalidOptions
	} else if err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	directory := filepath.Dir(path)
	if err := os.MkdirAll(directory, 0o755); err != nil {
		return err
	}
	temporary, err := os.CreateTemp(directory, ".manifest-gen-*.tmp")
	if err != nil {
		return err
	}
	temporaryPath := temporary.Name()
	committed := false
	defer func() {
		_ = temporary.Close()
		if !committed {
			_ = os.Remove(temporaryPath)
		}
	}()
	if err := temporary.Chmod(0o644); err != nil {
		return err
	}
	if _, err := temporary.Write(data); err != nil {
		return err
	}
	if err := temporary.Sync(); err != nil {
		return err
	}
	if err := temporary.Close(); err != nil {
		return err
	}
	if err := os.Rename(temporaryPath, path); err != nil {
		return err
	}
	committed = true
	return nil
}

func writeStringConstant(buffer *bytes.Buffer, name, value string) {
	fmt.Fprintf(buffer, "\t%s = %s\n", name, strconv.Quote(value))
}

func writeStringSliceAccessor(buffer *bytes.Buffer, name string, values []string) {
	fmt.Fprintf(buffer, "\nfunc %s() []string {\n", name)
	fmt.Fprintln(buffer, "\treturn []string{")
	for _, value := range values {
		fmt.Fprintf(buffer, "\t\t%s,\n", strconv.Quote(value))
	}
	fmt.Fprintln(buffer, "\t}")
	fmt.Fprintln(buffer, "}")
}
